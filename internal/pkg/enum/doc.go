package enum

import (
	"bytes"
	"fmt"
	"os"
	"regexp"
)

// goEnumDoc matches the two comment lines go-enum writes above a constant
// whose value carries a comment:
//
//	// DdvID is a EvenementType of type Ddv_ID.
//	// RDV de visite
var goEnumDoc = regexp.MustCompile(`(?m)^(\t// \S+ is an? \S+ of type )\S+\.\n\t// (.+)$`)

// RewriteDoc folds the comment of each value into the sentence go-enum writes
// above its constant: // DdvID is a EvenementType of type "RDV de visite".
// go-enum can only append the comment under its own sentence.
func RewriteDoc(src []byte) []byte {
	return goEnumDoc.ReplaceAll(src, []byte(`${1}"${2}".`))
}

// RewriteDocFiles applies RewriteDoc to files generated by go-enum, in place.
func RewriteDocFiles(files ...string) error {
	for _, file := range files {
		src, err := os.ReadFile(file)
		if err != nil {
			return fmt.Errorf("enum-doc: %w", err)
		}
		out := RewriteDoc(src)
		if bytes.Equal(out, src) {
			continue
		}
		//nolint:gosec // G306: generated Go source, readable like any source file.
		if err := os.WriteFile(file, out, 0o644); err != nil {
			return fmt.Errorf("enum-doc: %w", err)
		}
	}

	return nil
}
