func row(id int64, label string) Row {
	return Row{ID: sql.NullInt64{Int64: id, Valid: true}, Label: sql.NullString{String: label, Valid: true}}
}

var evenementType = Entry{Table: "public.evenement_type", ID: "id", Label: "label"}

func TestEntry_Names(t *testing.T) {
	tests := []struct {
		table                       string
		schema, name, typeName, pkg string
	}{
		{"public.evenement_type", "public", "evenement_type", "EvenementType", "evenementtype"},
		{"evenement_type", "public", "evenement_type", "EvenementType", "evenementtype"},
		{"core.event", "core", "event", "Event", "event"},
		{"ref.dossier_rel_status", "ref", "dossier_rel_status", "DossierRelStatus", "dossierrelstatus"},
	}

	for _, tt := range tests {
		t.Run(tt.table, func(t *testing.T) {
			e := Entry{Table: tt.table}
			if got := e.Schema(); got != tt.schema {
				t.Errorf("Schema() = %q, want %q", got, tt.schema)
			}
			if got := e.Name(); got != tt.name {
				t.Errorf("Name() = %q, want %q", got, tt.name)
			}
			if got := e.TypeName(); got != tt.typeName {
				t.Errorf("TypeName() = %q, want %q", got, tt.typeName)
			}
			if got := e.Package(); got != tt.pkg {
				t.Errorf("Package() = %q, want %q", got, tt.pkg)
			}
		})
	}
}

func TestRender(t *testing.T) {
	t.Run("output", func(t *testing.T) {
		want := `// Code generated by mmw db enum. DO NOT EDIT.

//go:generate go tool go-enum --values --noprefix
package evenementtype

import (
	"encoding/json"
	"fmt"
)

// EvenementType is a row of public.evenement_type.
// ENUM(
// rdv_d_estimation_ID=1,
// conge_ID=6,
// relance_r1_ID=28,
// )
type EvenementType int

// UnmarshalJSON reads the id and rejects one that is not a row of the table.
// null is rejected too: use a pointer for an optional value.
func (x *EvenementType) UnmarshalJSON(data []byte) error {
	// A pointer tells null from 0: json leaves a plain int untouched on null.
	var id *int
	if err := json.Unmarshal(data, &id); err != nil {
		return fmt.Errorf("EvenementType: %w", err)
	}
	if id == nil {
		return fmt.Errorf("null is %w", ErrInvalidEvenementType)
	}
	if !EvenementType(*id).IsValid() {
		return fmt.Errorf("%d is %w", *id, ErrInvalidEvenementType)
	}
	*x = EvenementType(*id)

	return nil
}
`
		got, err := Render(evenementType, []Row{row(1, "RDV d'estimation"), row(6, "Congé"), row(28, "Relance R1")})
		if err != nil {
			t.Fatalf("Render() error = %v", err)
		}
		if string(got) != want {
			t.Errorf("Render() =\n%s\nwant\n%s", got, want)
		}
	})
}

func commented(id int64, label, comment string) Row {
	r := row(id, label)
	r.Comment = sql.NullString{String: comment, Valid: true}

	return r
}

func TestRender_Comments(t *testing.T) {
	entry := Entry{Table: "public.evenement_type", ID: "id", Label: "sid", Comment: "label"}

	got, err := Render(entry, []Row{
		commented(1, "r1", "RDV d'estimation"),
		commented(6, "conge", "  Congé,\n payé\t(x)  "),
		commented(7, "perso", ""),
		commented(8, "autre", "R1 (bis"),
		row(28, "relance R1"),
	})
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}

	tests := []struct {
		name string
		line string
	}{
		{"go generate also rewrites the doc comments", "//go:generate go tool go-enum --values --noprefix\n//go:generate go tool mmw db enum-doc evenementtype_enum.go\npackage evenementtype\n"},
		{"the comment follows the value", "// r1_ID=1, // RDV d'estimation\n"},
		{"whitespace and line breaks collapse to one space", "// conge_ID=6, // Congé, payé (x)\n"},
		{"an empty comment adds nothing", "// perso_ID=7,\n"},
		{"a NULL comment adds nothing", "// relance_r1_ID=28,\n"},
		{"an unclosed parenthesis is kept: go-enum reads past it", "// autre_ID=8, // R1 (bis\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if !strings.Contains(string(got), tt.line) {
				t.Errorf("generated file does not contain %q:\n%s", tt.line, got)
			}
		})
	}
}

func TestRender_Errors(t *testing.T) {
	nullID := Row{Label: sql.NullString{String: "a", Valid: true}}
	nullLabel := Row{ID: sql.NullInt64{Int64: 3, Valid: true}}

	tests := []struct {
		name     string
		rows     []Row
		contains []string
		is       error
	}{
		{name: "no rows", contains: []string{"public.evenement_type", "no rows"}},
		{name: "NULL id", rows: []Row{nullID}, contains: []string{"NULL id"}},
		{name: "duplicate id", rows: []Row{row(1, "a"), row(1, "b")}, contains: []string{"duplicate id 1"}},
		{name: "NULL label", rows: []Row{nullLabel}, contains: []string{"id 3", "NULL label"}},
		{name: "empty stem", rows: []Row{row(3, "---")}, contains: []string{"id 3"}, is: ErrEmptyName},
		{name: "leading digit", rows: []Row{row(3, "1er RDV")}, contains: []string{"id 3"}, is: ErrLeadingDigit},
		{name: "names differing by case and accent", rows: []Row{row(6, "Congé"), row(9, "conge")}, contains: []string{"conge_ID", "6", "9"}},
		{name: "names giving the same Go constant", rows: []Row{row(28, "Relance R1"), row(34, "Relance R 1")}, contains: []string{"28", "34", "same Go constant"}},
		{name: "id zero", rows: []Row{row(0, "zero")}, contains: []string{"id 0", "want > 0"}},
		{name: "negative id", rows: []Row{row(-1, "minus")}, contains: []string{"id -1", "want > 0"}},
		{
			name:     "comment closing a parenthesis it did not open",
			rows:     []Row{commented(3, "a", "1) Visite"), row(4, "b")},
			contains: []string{"id 3", "1) Visite", "parenthesis"},
		},
		{
			name:     "comment closing more parentheses than it opens",
			rows:     []Row{commented(3, "a", "R1 (bis))")},
			contains: []string{"id 3", "parenthesis"},
		},
		{name: "names differing by apostrophe", rows: []Row{row(14, "RDV d'offre"), row(15, "RDV d’offre")}, contains: []string{"rdv_d_offre_ID", "14", "15"}},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Render(evenementType, tt.rows)
			if err == nil {
				t.Fatal("Render() error = nil, want an error")
			}
			for _, s := range tt.contains {
				if !strings.Contains(err.Error(), s) {
					t.Errorf("error %q does not contain %q", err, s)
				}
			}
			if tt.is != nil && !errors.Is(err, tt.is) {
				t.Errorf("error %q is not %v", err, tt.is)
			}
		})
	}
}
