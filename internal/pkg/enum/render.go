package enum

import (
	"database/sql"
	"fmt"
	"go/format"
	"strings"
	"unicode"
)

// Entry is one [[enum]] of the config file.
type Entry struct {
	// Table is "schema.table"; the schema defaults to public.
	Table string `toml:"table"`
	// ID is the column holding the integer value.
	ID string `toml:"id"`
	// Label is the column the value names are derived from.
	Label string `toml:"label"`
	// Comment is an optional column whose text is written next to each value,
	// and ends up in the doc comment of the constant.
	Comment string `toml:"comment"`
}

// Schema returns the schema of the table, public when Table names none.
func (e Entry) Schema() string {
	if schema, _, ok := strings.Cut(e.Table, "."); ok {
		return schema
	}

	return "public"
}

// Name returns the table name without its schema.
func (e Entry) Name() string {
	if _, name, ok := strings.Cut(e.Table, "."); ok {
		return name
	}

	return e.Table
}

// TypeName returns the Go type name: the table name in CamelCase.
func (e Entry) TypeName() string {
	var b strings.Builder
	for part := range strings.SplitSeq(e.Name(), "_") {
		runes := []rune(part)
		if len(runes) == 0 {
			continue
		}
		b.WriteRune(unicode.ToUpper(runes[0]))
		b.WriteString(string(runes[1:]))
	}

	return b.String()
}

// Package returns the Go package name, also the directory and file base name.
func (e Entry) Package() string {
	return strings.ToLower(e.TypeName())
}

// Row is one row of a lookup table, as read.
type Row struct {
	ID      sql.NullInt64
	Label   sql.NullString
	Comment sql.NullString
}

// unmarshalJSON is appended to every generated file; TYPE is the type name.
// IsValid and ErrInvalidTYPE come from the file go-enum generates next to it.
const unmarshalJSON = `
// UnmarshalJSON reads the id and rejects one that is not a row of the table.
// null is rejected too: use a pointer for an optional value.
func (x *TYPE) UnmarshalJSON(data []byte) error {
	// A pointer tells null from 0: json leaves a plain int untouched on null.
	var id *int
	if err := json.Unmarshal(data, &id); err != nil {
		return fmt.Errorf("TYPE: %w", err)
	}
	if id == nil {
		return fmt.Errorf("null is %w", ErrInvalidTYPE)
	}
	if !TYPE(*id).IsValid() {
		return fmt.Errorf("%d is %w", *id, ErrInvalidTYPE)
	}
	*x = TYPE(*id)

	return nil
}
`

// Render returns the gofmt-ed go-enum source file for e. rows must be ordered by id.
// It never renames or skips a row: any row that cannot be named is an error.
func Render(e Entry, rows []Row) ([]byte, error) {
	if len(rows) == 0 {
		return nil, fmt.Errorf("%s: no rows", e.Table)
	}

	var b strings.Builder
	b.WriteString("// Code generated by mmw db enum. DO NOT EDIT.\n\n")
	b.WriteString("//go:generate go tool go-enum --values --noprefix\n")
	if e.Comment != "" {
		// go generate runs the directives in order: go-enum, then the rewrite.
		fmt.Fprintf(&b, "//go:generate go tool mmw db enum-doc %s_enum.go\n", e.Package())
	}
	fmt.Fprintf(&b, "package %s\n\nimport (\n\t\"encoding/json\"\n\t\"fmt\"\n)\n\n", e.Package())
	fmt.Fprintf(&b, "// %s is a row of %s.%s.\n// ENUM(\n", e.TypeName(), e.Schema(), e.Name())

	ids := make(map[int64]bool, len(rows))
	names := make(map[string]int64, len(rows))
	for _, r := range rows {
		if !r.ID.Valid {
			return nil, fmt.Errorf("%s: a row has a NULL id in column %q", e.Table, e.ID)
		}
		id := r.ID.Int64
		if ids[id] {
			return nil, fmt.Errorf("%s: duplicate id %d in column %q", e.Table, id, e.ID)
		}
		ids[id] = true
		// 0 is the zero value of the type and what a failed Parse returns:
		// it must never be a valid row.
		if id <= 0 {
			return nil, fmt.Errorf("%s: invalid id %d in column %q (want > 0)", e.Table, id, e.ID)
		}

		if !r.Label.Valid {
			return nil, fmt.Errorf("%s: id %d has a NULL label in column %q", e.Table, id, e.Label)
		}
		name, err := CleanName(r.Label.String)
		if err != nil {
			return nil, fmt.Errorf("%s: id %d, label %q: %w", e.Table, id, r.Label.String, err)
		}
		// go-enum camel-cases a name by dropping its underscores, so
		// relance_r1_ID and relance_r_1_ID are the same Go constant.
		key := strings.ReplaceAll(name, "_", "")
		if other, ok := names[key]; ok {
			return nil, fmt.Errorf("%s: ids %d and %d give the same Go constant (%s)", e.Table, other, id, name)
		}
		names[key] = id

		fmt.Fprintf(&b, "// %s=%d,", name, id)
		// strings.Fields also drops line breaks, which would end the comment.
		comment := strings.Join(strings.Fields(r.Comment.String), " ")
		// go-enum finds the end of ENUM( by counting parentheses on the whole
		// line, comment included: one ")" too many ends the enum there, and
		// the rows after it are dropped without an error.
		if strings.Count(comment, ")") > strings.Count(comment, "(") {
			return nil, fmt.Errorf(
				"%s: id %d, comment %q: a closing parenthesis without its opening one would cut the enum short",
				e.Table, id, comment)
		}
		if comment != "" {
			fmt.Fprintf(&b, " // %s", comment)
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "// )\ntype %s int\n", e.TypeName())
	b.WriteString(strings.ReplaceAll(unmarshalJSON, "TYPE", e.TypeName()))

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("%s: formatting generated source: %w", e.Table, err)
	}

	return src, nil
}
