package db

import (
	"github.com/piprim/mmw/internal/pkg/enum"
	"github.com/spf13/cobra"
)

func NewEnumCmd() *cobra.Command {
	var opts enum.Options

	cmd := &cobra.Command{
		Use:   "enum",
		Short: "Generate go-enum source files from the rows of lookup tables",
		Long: `Reads the lookup tables of a config file and writes one Go package per table,
holding a go-enum source file with one value per row. Run go generate on the
output directory afterwards. See internal/pkg/enum/README.md.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			opts.Stdout = cmd.OutOrStdout()

			return enum.Run(cmd.Context(), &opts)
		},
	}

	flags := cmd.Flags()
	flags.StringVarP(&opts.URL, "conn", "c", "",
		"connection string, e.g. postgres://user:password@localhost:5432/db?sslmode=disable")
	flags.StringVar(&opts.Config, "config", "", "enum configuration file")
	_ = cmd.MarkFlagRequired("conn")
	_ = cmd.MarkFlagRequired("config")

	return cmd
}

func NewEnumDocCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "enum-doc <file>...",
		Short: "Fold the value comments into the doc comments go-enum generated",
		Long: `Rewrites files generated by go-enum so that the comment of each value replaces
the value name in the doc comment of its constant. mmw db enum adds a
go:generate line calling it when an entry has a comment column.`,
		Args: cobra.MinimumNArgs(1),
		RunE: func(_ *cobra.Command, args []string) error {
			return enum.RewriteDocFiles(args...)
		},
	}
}
